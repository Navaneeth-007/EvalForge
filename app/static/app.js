const question = document.querySelector('#question');
const schema = document.querySelector('#schema');
const button = document.querySelector('#generate');
const sql = document.querySelector('#sql');
const error = document.querySelector('#error');
const copy = document.querySelector('#copy');
async function initialize() {
  try {
    const response = await fetch('/examples');
    if (!response.ok) throw new Error('Unable to load examples. Please refresh.');
    const data = await response.json();
    question.replaceChildren(...data.examples[0].sample_questions.map(text => {
      const option = document.createElement('option'); option.textContent = text; return option;
    }));
    schema.value = data.examples[0].schema;
    document.querySelector('#mode').textContent = data.mode === 'model' ? 'Adapter inference' : 'Authored example mode';
    if (data.mode === 'model') {
      button.textContent = 'Generate SQL →';
      document.querySelector('#notice').textContent = 'SQL is generated by the configured adapter. Inspect the query before using it. Queries are not executed by this service.';
      document.querySelector('#source').textContent = 'Source: configured adapter';
    }
    button.disabled = false;
  } catch (e) { error.textContent = e.message; document.querySelector('#mode').textContent = 'Service unavailable'; }
}
button.addEventListener('click', async () => {
  button.disabled = true; error.textContent = ''; copy.disabled = true;
  try {
    const response = await fetch('/generate-sql', {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({question: question.value, schema: schema.value})});
    const data = await response.json();
    if (!response.ok) throw new Error(typeof data.detail === 'string' ? data.detail : 'Please check the question and schema.');
    sql.textContent = data.sql;
    document.querySelector('#latency').textContent = `${data.latency_ms} ms`;
    document.querySelector('#source').textContent = `Source: ${data.model}`;
    copy.disabled = false;
  } catch (e) { error.textContent = e.message; }
  finally { button.disabled = false; }
});
copy.addEventListener('click', async () => {
  try { await navigator.clipboard.writeText(sql.textContent); copy.textContent = 'Copied'; }
  catch { error.textContent = 'Select the SQL output to copy it manually.'; }
});
initialize();
