const question = document.querySelector('#question');
const schema = document.querySelector('#schema');
const button = document.querySelector('#generate');
const sql = document.querySelector('#sql');
const error = document.querySelector('#error');
const copy = document.querySelector('#copy');
let recorded = null;
async function initialize() {
  try {
    const response = await fetch('/examples');
    if (!response.ok) throw new Error('Unable to load examples. Please refresh.');
    const data = await response.json();
    question.replaceChildren(...data.examples[0].sample_questions.map(text => {
      const option = document.createElement('option'); option.textContent = text; return option;
    }));
    schema.value = data.examples[0].schema;
    document.querySelector('#mode').textContent = data.mode === 'model' ? 'Adapter inference' : 'Authored example mode';
    if (data.mode === 'model') {
      button.textContent = 'Generate SQL →';
      document.querySelector('#notice').textContent = 'SQL is generated by the configured adapter. Inspect the query before using it. Queries are not executed by this service.';
      document.querySelector('#source').textContent = 'Source: configured adapter';
    }
    const evidenceResponse = await fetch('/results');
    if (evidenceResponse.ok) {
      const evidence = await evidenceResponse.json();
      if (evidence.kind === 'recorded_predictions') {
        recorded = evidence;
        question.replaceChildren(...evidence.predictions.map((item, index) => {
          const option = document.createElement('option'); option.value = String(index); option.textContent = item.question; return option;
        }));
        schema.value = evidence.predictions[0].schema;
        button.textContent = 'Compare recorded predictions →';
        document.querySelector('#mode').textContent = 'Recorded GPU pilot';
        document.querySelector('#notice').textContent = evidence.message;
        document.querySelector('#evidence-title').textContent = 'A measured first experiment.';
        document.querySelector('#evidence-description').textContent = `${evidence.experiment.train_examples} training examples · ${evidence.training_config.num_train_epochs} epoch · ${evidence.evaluation.n} held-out development examples · ${evidence.experiment.gpu}. Pilot results, not an independent test benchmark. Values below show base → adapter.`;
        const format = value => value == null ? 'Not measured' : `${(value * 100).toFixed(1)}%`;
        const values = document.querySelectorAll('.metric-value');
        ['exact_match', 'execution_accuracy', 'bleu4'].forEach((key, index) => {
          values[index].textContent = `${format(evidence.metrics.base[key])} → ${format(evidence.metrics.adapter[key])}`;
        });
        values[2].parentElement.querySelector('span').textContent = 'BLEU-4 (BERTScore skipped)';
      }
    }
    button.disabled = false;
  } catch (e) { error.textContent = e.message; document.querySelector('#mode').textContent = 'Service unavailable'; }
}
button.addEventListener('click', async () => {
  button.disabled = true; error.textContent = ''; copy.disabled = true;
  try {
    if (recorded) {
      const item = recorded.predictions[Number(question.value)];
      sql.textContent = item.finetuned_prediction;
      document.querySelector('#base-sql').textContent = item.base_prediction;
      document.querySelector('#gold-sql').textContent = item.sql;
      document.querySelector('#base-comparison').hidden = false;
      document.querySelector('#reference').hidden = false;
      document.querySelector('#source').textContent = `Source: recorded Phi-3 QLoRA pilot · database ${item.db_id}`;
      document.querySelector('#latency').textContent = 'Recorded comparison';
      copy.disabled = false;
      return;
    }
    const response = await fetch('/generate-sql' , {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({question: question.value, schema: schema.value})});
    const data = await response.json();
    if (!response.ok) throw new Error(typeof data.detail === 'string' ? data.detail : 'Please check the question and schema.');
    sql.textContent = data.sql;
    document.querySelector('#latency').textContent = `${data.latency_ms} ms`;
    document.querySelector('#source').textContent = `Source: ${data.model}`;
    copy.disabled = false;
  } catch (e) { error.textContent = e.message; }
  finally { button.disabled = false; }
});
copy.addEventListener('click', async () => {
  try { await navigator.clipboard.writeText(sql.textContent); copy.textContent = 'Copied'; }
  catch { error.textContent = 'Select the SQL output to copy it manually.'; }
});
initialize();

question.addEventListener('change', () => {
  if (recorded) schema.value = recorded.predictions[Number(question.value)].schema;
  sql.textContent = '-- Select compare to inspect this question.';
  document.querySelector('#base-comparison').hidden = true;
  document.querySelector('#reference').hidden = true;
  copy.disabled = true;
});
